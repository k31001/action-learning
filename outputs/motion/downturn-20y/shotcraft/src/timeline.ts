const seq = <K extends string>(list: [K, number][]) => {
  let at = 0;
  const out = {} as Record<K, { from: number; dur: number }>;
  for (const [k, d] of list) { out[k] = { from: at, dur: d }; at += d; }
  return { shots: out, total: at };
};

