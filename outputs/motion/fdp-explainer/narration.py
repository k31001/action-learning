"""「FDP가 뭐야?」 30초 설명 영상 — 내레이션 합성 (여성 성우 · Microsoft Edge 신경망 TTS ko-KR-SunHiNeural)

  python -m venv .venv-tts && .venv-tts/bin/pip install edge-tts
  .venv-tts/bin/python outputs/motion/fdp-explainer/narration.py
    → narration.mp3 (30초 타임라인에 대사를 배치한 완성 트랙) + cues.js (대사 시작·끝 시각, index.html이 읽음)

대사(LINES)의 표기는 발음용이다(에프디피·더블유에이에프). 화면 자막은 index.html의 SUBS가 따로 갖는다.
TTS 클립은 앞뒤 무음을 잘라 앞 대사 끝 + 간격에 놓는다. 마지막 대사가 DURATION - TAIL을 넘으면 오류로 멈춘다.
프록시 CA를 쓰는 환경이면 SSL_CERT_FILE(예: /root/.ccr/ca-bundle.crt)을 지정한다.
"""
import asyncio
import json
import os
import ssl
import subprocess
import tempfile

import edge_tts
import edge_tts.communicate as _comm

DIR = os.path.dirname(os.path.abspath(__file__))
VOICE = "ko-KR-SunHiNeural"
RATE = "+22%"
DURATION = 30.0

TAIL = 0.6  # 마지막 대사 뒤 여운

# (앞 대사 끝에서 띄우는 간격 s, 발음용 대사) — 첫 간격은 영상 시작 기준
LINES = [
    (0.40, "에프디피는 데이터를 어디에 쓸지 호스트가 SSD에 알려 주는 기능입니다."),
    (0.30, "SSD는 페이지로 쓰고, 블록으로 지웁니다."),
    (0.25, "세션이 한 블록에 섞이면 지우기 전에 남은 데이터를 옮겨야 하는데, 이 추가 쓰기가 더블유에이에프입니다."),
    (0.35, "에프디피로 세션마다 블록을 나누면, 통째로 지워져 복사가 없습니다."),
    (0.45, "시뮬레이션에서, 에프디피 없이 3.6이던 더블유에이에프가,"),
    (0.15, "핸들 8개면 1.7, 16개면 1.1로 떨어집니다."),
    (0.40, "같은 수명은 같은 블록에. 그것이 에프디피입니다."),
]

if os.environ.get("SSL_CERT_FILE"):
    _comm._SSL_CTX = ssl.create_default_context(cafile=os.environ["SSL_CERT_FILE"])


def ff(*args):
    subprocess.run(["ffmpeg", "-nostdin", "-loglevel", "error", "-y", *args], check=True)


def probe(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                         check=True, capture_output=True, text=True).stdout
    return float(out)


async def synth(text, path):
    await edge_tts.Communicate(text, VOICE, rate=RATE).save(path)


def main():
    tmp = tempfile.mkdtemp(prefix="fdp-nar-")
    clips, cues, t = [], [], 0.0
    for i, (gap, text) in enumerate(LINES):
        at = round(t + gap, 3)
        raw, cut = os.path.join(tmp, f"l{i}.mp3"), os.path.join(tmp, f"c{i}.wav")
        asyncio.run(synth(text, raw))
        trim = "silenceremove=start_periods=1:start_threshold=-45dB"
        ff("-i", raw, "-af", f"{trim},areverse,{trim},areverse", "-ar", "48000", "-ac", "1", cut)
        t = at + probe(cut)
        clips.append((at, cut))
        cues.append({"at": at, "end": round(t, 3)})
        print(f"{i + 1}  {at:5.2f} → {t:5.2f}  {text}")
    if t > DURATION - TAIL:
        raise SystemExit(f"내레이션이 {t - DURATION + TAIL:.2f}s 넘친다 — 대사를 줄이거나 RATE를 올린다")

    inputs, chains = [], []
    for k, (at, cut) in enumerate(clips):
        inputs += ["-i", cut]
        ms = int(at * 1000)
        chains.append(f"[{k}]adelay={ms}|{ms}[d{k}]")
    mix = "".join(f"[d{k}]" for k in range(len(clips)))
    fc = ";".join(chains) + f";{mix}amix=inputs={len(clips)}:normalize=0,apad,atrim=0:{DURATION}," \
         "loudnorm=I=-16:TP=-1.5:LRA=11,aresample=48000"
    ff(*inputs, "-filter_complex", fc, "-ac", "2", "-c:a", "libmp3lame", "-b:a", "192k",
       os.path.join(DIR, "narration.mp3"))
    with open(os.path.join(DIR, "cues.js"), "w", encoding="utf-8") as f:
        f.write("// GENERATED by narration.py — 대사 시작·끝 시각(초)\nwindow.CUES = "
                + json.dumps(cues) + ";\n")
    print("narration.mp3 · cues.js")


if __name__ == "__main__":
    main()
